// "01", "02", ...
export function statementNumber(index: number) {
  return String(index + 1).padStart(2, "0");
}

// URL anchor for a statement on the full page, e.g. "baptism-and-the-lords-supper"
export function statementSlug(statement: Statement) {
  return statement.title
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[’']/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
